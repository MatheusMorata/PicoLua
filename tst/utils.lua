--------------------------------------------------
-- DESENHA A CENA COMPLETA
--------------------------------------------------

function utils.desenhar(
    pico,
    nave,
    inimigos,
    tiro,
    pontos,
    pausado
)

    --------------------------------------------------
    -- LIMPA A TELA
    --------------------------------------------------

    pico.output.clear()


    --------------------------------------------------
    -- INIMIGOS
    --------------------------------------------------

    utils.inimigos(
        pico,
        inimigos
    )


    --------------------------------------------------
    -- NAVE
    --------------------------------------------------

    utils.nave(
        pico,
        nave
    )


    --------------------------------------------------
    -- TIRO
    --------------------------------------------------

    if tiro then

        utils.tiro(
            pico,
            tiro
        )

    end


    --------------------------------------------------
    -- PONTUAÇÃO
    --------------------------------------------------

    utils.pontuacao(
        pico,
        pontos
    )


    --------------------------------------------------
    -- PAUSE
    --------------------------------------------------

    if pausado then

        utils.pause(
            pico
        )

    end

end


