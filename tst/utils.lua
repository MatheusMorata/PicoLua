    -- RESTAURA COR
    --------------------------------------------------

    pico.set.color_draw({

        r = 255,

        g = 255,

        b = 255,

        a = 255

    })


    --------------------------------------------------
    -- RESTAURA ÂNCORA
    --------------------------------------------------

    pico.set.anchor_draw({

        x = PICO_CENTER,

        y = PICO_MIDDLE

    })

end


--------------------------------------------------
-- DESENHA TODOS OS INIMIGOS
--------------------------------------------------

function utils.inimigos(
    pico,
    inimigos
)

    --------------------------------------------------
    -- ÂNCORA SUPERIOR ESQUERDA
    --------------------------------------------------

    pico.set.anchor_draw({

        x = PICO_LEFT,

        y = PICO_TOP

    })


    --------------------------------------------------
    -- COR DOS INIMIGOS
    --------------------------------------------------

    pico.set.color_draw({

        r = 255,

        g = 0,

        b = 0,

        a = 255

    })


    --------------------------------------------------
    -- DESENHA SOMENTE OS INIMIGOS VIVOS
    --------------------------------------------------

    for _, enemy in ipairs(inimigos) do

        if enemy.vivo then

            desenhar_inimigo(
                pico,
                enemy
            )

        end

    end


    --------------------------------------------------
    -- RESTAURA COR
    --------------------------------------------------

    pico.set.color_draw({

        r = 255,

        g = 255,

        b = 255,

        a = 255

    })


    --------------------------------------------------
    -- RESTAURA ÂNCORA
    --------------------------------------------------

    pico.set.anchor_draw({

        x = PICO_CENTER,

        y = PICO_MIDDLE

    })

end


--------------------------------------------------
-- NAVE
--------------------------------------------------

function utils.nave(
    pico,
    nave
)

    --------------------------------------------------
    -- ÂNCORA SUPERIOR ESQUERDA
    --------------------------------------------------

    pico.set.anchor_draw({

        x = PICO_LEFT,

        y = PICO_TOP

    })


    --------------------------------------------------
    -- COR DA NAVE
    --------------------------------------------------

    pico.set.color_draw({

        r = 0,

        g = 255,

        b = 0,

        a = 255

    })


    local cx = nave.x

    local cy = nave.y


    --------------------------------------------------
    -- PIXELS DA NAVE
    --------------------------------------------------

    local pixels = {

        --------------------------------------------------
        -- PONTA
        --------------------------------------------------

        {
            x = cx + 0,
            y = cy + 0
        },


        --------------------------------------------------
        -- SEGUNDA LINHA
        --------------------------------------------------

        {
            x = cx - 1,
            y = cy + 1
        },

        {
            x = cx + 0,
            y = cy + 1
        },

        {
            x = cx + 1,
            y = cy + 1
        },


        --------------------------------------------------
        -- TERCEIRA LINHA
        --------------------------------------------------

        {
            x = cx - 2,
            y = cy + 2
        },

        {
            x = cx - 1,
            y = cy + 2
        },

        {
            x = cx + 0,
            y = cy + 2
        },

        {
            x = cx + 1,
            y = cy + 2
        },

        {
            x = cx + 2,
            y = cy + 2
        },


        --------------------------------------------------
        -- BASE
        --------------------------------------------------

        {
            x = cx - 3,
            y = cy + 3
        },

        {
            x = cx - 2,
            y = cy + 3
        },

        {
            x = cx - 1,
            y = cy + 3
        },

        {
            x = cx + 0,
            y = cy + 3
        },

        {
            x = cx + 1,
            y = cy + 3
        },

        {
            x = cx + 2,
            y = cy + 3
        },

        {
            x = cx + 3,
            y = cy + 3
        },


        --------------------------------------------------
        -- MOTORES
        --------------------------------------------------

        {
            x = cx - 2,
            y = cy + 4
        },

        {
            x = cx + 2,
            y = cy + 4
        }

    }


    --------------------------------------------------
    -- DESENHA OS PIXELS
    --------------------------------------------------

    pico.output.draw_pixels(
        pixels,
        #pixels
    )


    --------------------------------------------------
    -- RESTAURA COR
    --------------------------------------------------

    pico.set.color_draw({

        r = 255,

        g = 255,

        b = 255,

        a = 255

    })


    --------------------------------------------------
    -- RESTAURA ÂNCORA
    --------------------------------------------------

    pico.set.anchor_draw({

        x = PICO_CENTER,

        y = PICO_MIDDLE

    })

end


